CREATE TABLE IF NOT EXISTS users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    email TEXT NOT NULL UNIQUE,
    role TEXT NOT NULL CHECK (
        role IN ('USER', 'HOST', 'MODERATOR')
    ),
    reputation NUMERIC(3, 2) NOT NULL DEFAULT 3.00
        CHECK (reputation >= 1.00 AND reputation <= 5.00),
    is_banned BOOLEAN NOT NULL DEFAULT FALSE,


    password_hash TEXT NOT NULL
);



CREATE TABLE IF NOT EXISTS sessions (
    token_hash TEXT PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    expires_at TIMESTAMPTZ NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_sessions_user
    ON sessions(user_id);

CREATE INDEX IF NOT EXISTS idx_sessions_expiry
    ON sessions(expires_at);



CREATE TABLE IF NOT EXISTS events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    host_id BIGINT NOT NULL REFERENCES users(id),
    title TEXT NOT NULL,
    description TEXT NOT NULL,

    state TEXT NOT NULL CHECK (
        state IN (
            'PRELIMINARY',
            'PUBLISHED',
            'ONGOING',
            'COMPLETED',
            'CANCELLED'
        )
    ),

    capacity INTEGER NOT NULL CHECK (capacity > 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_events_host
    ON events(host_id);

CREATE INDEX IF NOT EXISTS idx_events_state
    ON events(state);



CREATE TABLE IF NOT EXISTS registrations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id BIGINT NOT NULL REFERENCES events(id),
    user_id BIGINT NOT NULL REFERENCES users(id),

    status TEXT NOT NULL DEFAULT 'ACTIVE' CHECK (
        status IN ('ACTIVE', 'CANCELLED')
    ),

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);


CREATE UNIQUE INDEX IF NOT EXISTS idx_one_active_registration
    ON registrations(event_id, user_id)
    WHERE status = 'ACTIVE';

CREATE INDEX IF NOT EXISTS idx_registrations_event
    ON registrations(event_id);




CREATE TABLE IF NOT EXISTS reviews (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id BIGINT NOT NULL REFERENCES events(id),
    author_id BIGINT NOT NULL REFERENCES users(id),

    rating INTEGER NOT NULL CHECK (
        rating >= 1 AND rating <= 5
    ),

    comment TEXT NOT NULL CHECK (
        LENGTH(TRIM(comment)) BETWEEN 5 AND 500
    ),

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),


    UNIQUE(event_id, author_id)
);
